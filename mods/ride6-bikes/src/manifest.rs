//! The files around a bike's geometry: the mod's `mod.toml` and the car's manifest `cars/<id>.toml`.
//!
//! The manifest is a bike (`kind = "bike"`, `docs/modding/bikes.md`): the names, `[wheels]` (where the model has its two
//! hubs), the `[bike]` table converted from the bike's physics data ([`crate::bike_table`]) and, when the `sound` command
//! has run, its `[engine_sound]` and `[car_sound]` tables ([`crate::manifest_sound`]). A bike has no `[stats]`: the game
//! derives the numbers the shop and the lists show from `[bike]`.

use std::path::Path;

use anyhow::{Context, Result};

use crate::bike_table::BikeTable;
use crate::build::{Built, Wheel};
use crate::physics::toml_text::{Toml, quote};

/// The `mod.toml` of the content mod: no library, only `cars/` and `files/`.
pub const MOD_TOML: &str = r#"# Bikes of the user's own RIDE 6 install, converted by `ride6-bike-import` (mods/ride6-bikes/README.md).
# A content-only mod: it holds `cars/` and `files/` and no library. The generated files belong to the user's install
# of RIDE 6 and are never committed.

[mod]
id = "ride6-bikes"
name = "RIDE 6 bikes"
version = "0.1.0"
authors = ["nfs-mw contributors"]
license = "MIT OR Apache-2.0"

[api]
blackbox_modding = "0.1"

[games]
supported = ["nfsmw"]
"#;

/// What goes into a manifest besides the names and the wheels.
pub struct Tables<'a> {
    /// The `[bike]` table.
    pub bike: &'a BikeTable,
    /// The text of the `sound` command's tables, when it has run.
    pub sound: Option<&'a str>,
}

/// One wheel's `[wheels.<side>]` table: where the model has the hub, and the tyre's size. A bike's wheel is on the centre
/// line, so there is no `face_m`.
fn wheel_table(t: &mut Toml, side: &str, wheel: &Wheel) {
    t.table(&format!("wheels.{side}"));
    t.num("x_m", f64::from(wheel.hub[0]));
    t.num("z_m", f64::from(wheel.hub[2]));
    t.num("radius_m", f64::from(wheel.radius));
    t.num("width_m", f64::from(wheel.width));
}

/// The text of `cars/<id>.toml`.
pub fn car_toml(name: &str, manufacturer: &str, built: &Built, tables: &Tables<'_>) -> String {
    let mut text = format!(
        "# {name} of RIDE 6 as a bike of NFS: Most Wanted. Generated by `ride6-bike-import`.\n\
         # [wheels]: the hubs in the body solid's frame (x forward, z up), metres. [bike]: converted from the bike's physics data\n\
         # (docs/modding/ride6-bikes.md); a bike has no stats table.\n\
         kind = \"bike\"\nrole = \"player\"\nname = {}\nmanufacturer = {}\n",
        quote(name),
        quote(manufacturer)
    );
    let mut wheels = Toml::new();
    wheel_table(&mut wheels, "front", &built.front);
    wheel_table(&mut wheels, "rear", &built.rear);
    text.push('\n');
    text.push_str(&wheels.into_string());
    text.push('\n');
    text.push_str(&tables.bike.text);
    if let Some(sound) = tables.sound {
        text.push('\n');
        text.push_str(sound);
    }
    text
}

/// Write the mod's files into `mod_dir`: `mod.toml`, `cars/<id>.toml` and `files/CARS/<ID>/`.
pub fn write(mod_dir: &Path, folder: &str, names: (&str, &str), built: &Built, tables: &Tables<'_>) -> Result<()> {
    write_car(mod_dir, folder, names, built, tables)?;
    write_mod_toml(mod_dir)
}

/// Write one car: `files/CARS/<ID>/` and `cars/<id>.toml`, not `mod.toml` (a batch writes that once, so that cars written
/// side by side by several threads do not race on it).
pub fn write_car(mod_dir: &Path, folder: &str, names: (&str, &str), built: &Built, tables: &Tables<'_>) -> Result<()> {
    let id = folder.to_ascii_uppercase();
    let car_dir = mod_dir.join("files").join("CARS").join(&id);
    std::fs::create_dir_all(&car_dir).with_context(|| format!("creating {}", car_dir.display()))?;
    for (file, bytes) in
        [("GEOMETRY.BIN", &built.geometry), ("TEXTURES.BIN", &built.textures), ("BOUNDS.BIN", &built.bounds)]
    {
        std::fs::write(car_dir.join(file), bytes).with_context(|| format!("writing {file}"))?;
    }
    write_car_manifest(mod_dir, folder, names, built, tables)
}

/// Write `cars/<id>.toml` only (the car's files are not touched).
pub fn write_car_manifest(
    mod_dir: &Path,
    folder: &str,
    (name, manufacturer): (&str, &str),
    built: &Built,
    tables: &Tables<'_>,
) -> Result<()> {
    let id = folder.to_ascii_uppercase();
    std::fs::create_dir_all(mod_dir.join("cars"))?;
    let manifest = mod_dir.join("cars").join(format!("{}.toml", id.to_ascii_lowercase()));
    std::fs::write(manifest, car_toml(name, manufacturer, built, tables))?;
    Ok(())
}

/// Write the content-only `mod.toml`, unless the folder has one already: the mod's own folder has a `mod.toml` that declares
/// its native library (`mods/ride6-bikes/mod.toml`), which the importer must not replace.
pub fn write_mod_toml(mod_dir: &Path) -> Result<()> {
    std::fs::create_dir_all(mod_dir)?;
    let file = mod_dir.join("mod.toml");
    if file.exists() {
        return Ok(());
    }
    std::fs::write(file, MOD_TOML)?;
    Ok(())
}

/// Write `mod.toml` and `cars/<id>.toml` only (the car's files are not touched): what `remanifest` does when the physics
/// data is converted again.
pub fn write_manifest(
    mod_dir: &Path,
    folder: &str,
    names: (&str, &str),
    built: &Built,
    tables: &Tables<'_>,
) -> Result<()> {
    write_car_manifest(mod_dir, folder, names, built, tables)?;
    write_mod_toml(mod_dir)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn built() -> Built {
        let wheel = |x: f32, radius: f32, width: f32| Wheel { hub: [x, 0.0, radius], radius, width };
        Built {
            geometry: vec![],
            textures: vec![],
            bounds: vec![],
            half: [0.4, 0.6, 1.0],
            front: wheel(0.7355, 0.288, 0.12),
            rear: wheel(-0.739, 0.312, 0.16),
            triangles: 0,
            front_end: Default::default(),
            exhaust: Vec::new(),
        }
    }

    #[test]
    fn the_manifest_is_a_bike_with_its_hubs_and_no_stats() {
        let bike = BikeTable { text: "[bike]\ndrag = 0.15\n".to_owned(), notes: vec![] };
        let tables = Tables { bike: &bike, sound: Some("[engine_sound]\nidle_rpm = 2300.0\n") };
        let text = car_toml("KTM \"450\" SMR", "KTM", &built(), &tables);
        assert!(text.contains("\nkind = \"bike\"\n"));
        assert!(text.contains("name = \"KTM \\\"450\\\" SMR\""));
        assert!(text.contains("[wheels.front]\nx_m = 0.7355\nz_m = 0.288\nradius_m = 0.288\nwidth_m = 0.12\n"));
        assert!(text.contains("[wheels.rear]\nx_m = -0.739\nz_m = 0.312\nradius_m = 0.312\nwidth_m = 0.16\n"));
        assert!(!text.contains("face_m") && !text.contains("[stats]"));
        assert!(text.contains("\n[bike]\ndrag = 0.15\n"));
        assert!(text.ends_with("[engine_sound]\nidle_rpm = 2300.0\n"));
    }
}
