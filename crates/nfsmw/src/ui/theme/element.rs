//! The MW element catalogue: every slot a theme may replace in NFS:MW, with the number the registry keys it by.
//!
//! The numbers are part of the mod ABI (`bb.ui`, `docs/specs/ui-themes.md` section 12): they are written out
//! explicitly and never reused. Do not renumber a variant, and do not derive a number from the variant's
//! position (`self as u32`), so inserting a variant cannot shift the ids of the others. A retired slot keeps its
//! number and is removed from [`ElementId::ALL`] only.
//!
//! Each slot's Original source is recorded in `docs/specs/ui-themes.md` section 6.
//!
//! The enum is generated by [`catalogue!`] so that [`ElementId::ALL`], [`ElementId::raw`] and
//! [`ElementId::name`] cannot drift from the variant list.

use blackbox_ui::SlotId;

impl ElementId {
    /// Whether the slot is a menu or career screen (raw 20 and up), which the menu cell feeds, rather than a HUD slot.
    /// The world-map chrome is numbered with the frontend block but is not menu-cell-fed (it is drawn as its own overlay
    /// layer), so it is not a menu slot.
    pub const fn is_menu(self) -> bool {
        self.raw() >= 20 && !matches!(self, ElementId::WorldMapChrome)
    }
}

/// Declares the enum with one explicit number per variant, and the const tables built from the same list.
macro_rules! catalogue {
    ($( $variant:ident = $id:literal ),+ $(,)?) => {
        #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
        pub enum ElementId {
            $( $variant, )+
        }

        impl ElementId {
            /// Every slot, in catalogue order.
            pub const ALL: &'static [ElementId] = &[ $( ElementId::$variant, )+ ];

            /// The stable number the registry keys this slot by.
            pub const fn raw(self) -> u32 {
                match self {
                    $( ElementId::$variant => $id, )+
                }
            }

            /// The variant name, for the console and the mod listing.
            pub const fn name(self) -> &'static str {
                match self {
                    $( ElementId::$variant => stringify!($variant), )+
                }
            }

            /// The slot the theme registry is asked for.
            pub const fn slot(self) -> SlotId {
                SlotId::new(self.raw())
            }

            /// The element a registry slot id names, or `None` for an id this catalogue does not list.
            pub fn from_slot(slot: SlotId) -> Option<Self> {
                Self::ALL.iter().copied().find(|element| element.slot() == slot)
            }
        }
    };
}

